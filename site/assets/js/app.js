  function validate(form) {
    let ok = true;
    $$("[required]", form).forEach((el) => {
      const f = el.closest(".field");
      const bad = el.type === "checkbox" ? !el.checked : el.type === "file" ? !el.files.length : el.type === "email" ? !/^\S+@\S+\.\S+$/.test(el.value) : !el.value.trim();
      f?.classList.toggle("error", bad);
      el.setAttribute("aria-invalid", bad);
      if (bad && ok) { (el.type === "file" ? el.closest(".dropzone") : el).focus?.(); ok = false; }
    });
    return ok;
  }

